-- Compartimentos do armazém. O tipo atual é definido pela primeira entrada e a
-- quantidade_atual é um total desnormalizado mantido na mesma transação das
-- movimentações. Assim o espaço livre sai em O(1), sem somar ingredientes ou histórico.
CREATE TABLE compartimento (
    id                     BIGINT         NOT NULL PRIMARY KEY,
    codigo                 VARCHAR(5)     NOT NULL,
    tipo_atual             VARCHAR(20),
    quantidade_atual       NUMERIC(12, 3) NOT NULL DEFAULT 0,
    ultima_movimentacao_em DATE,
    versao                 BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_compartimento_codigo UNIQUE (codigo),
    CONSTRAINT ck_compartimento_quantidade CHECK (quantidade_atual >= 0),
    CONSTRAINT ck_compartimento_tipo CHECK (tipo_atual IN ('SECO', 'LIQUIDO', 'REFRIGERADO'))
);

CREATE TABLE ingrediente (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(120)   NOT NULL,
    nome_normalizado VARCHAR(120)   NOT NULL,
    tipo             VARCHAR(20)    NOT NULL,
    quantidade       NUMERIC(12, 3) NOT NULL,
    compartimento_id BIGINT         NOT NULL,
    criado_em        TIMESTAMP(6)   NOT NULL,
    atualizado_em    TIMESTAMP(6)   NOT NULL,
    versao           BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT fk_ingrediente_compartimento FOREIGN KEY (compartimento_id) REFERENCES compartimento (id),
    CONSTRAINT uk_ingrediente_compartimento_tipo_nome UNIQUE (compartimento_id, tipo, nome_normalizado),
    CONSTRAINT ck_ingrediente_quantidade CHECK (quantidade >= 0),
    CONSTRAINT ck_ingrediente_tipo CHECK (tipo IN ('SECO', 'LIQUIDO', 'REFRIGERADO'))
);

CREATE INDEX idx_ingrediente_tipo ON ingrediente (tipo);

-- Histórico imutável de entradas e saídas. nome_ingrediente e compartimento_codigo
-- guardam uma fotografia do momento da operação, para auditoria.
CREATE TABLE movimentacao (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora            TIMESTAMP(6)   NOT NULL,
    tipo_operacao        VARCHAR(10)    NOT NULL,
    quantidade           NUMERIC(12, 3) NOT NULL,
    tipo_ingrediente     VARCHAR(20)    NOT NULL,
    responsavel          VARCHAR(100)   NOT NULL,
    ingrediente_id       BIGINT         NOT NULL,
    nome_ingrediente     VARCHAR(120)   NOT NULL,
    compartimento_id     BIGINT         NOT NULL,
    compartimento_codigo VARCHAR(5)     NOT NULL,
    saldo_compartimento  NUMERIC(12, 3) NOT NULL,
    CONSTRAINT fk_movimentacao_ingrediente FOREIGN KEY (ingrediente_id) REFERENCES ingrediente (id),
    CONSTRAINT fk_movimentacao_compartimento FOREIGN KEY (compartimento_id) REFERENCES compartimento (id),
    CONSTRAINT ck_movimentacao_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_movimentacao_operacao CHECK (tipo_operacao IN ('ENTRADA', 'SAIDA'))
);

CREATE INDEX idx_movimentacao_data_hora ON movimentacao (data_hora);
CREATE INDEX idx_movimentacao_compartimento_data ON movimentacao (compartimento_id, data_hora);

